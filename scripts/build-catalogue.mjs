/* ─────────────── parse page-html ─────────────── */
const clean = s => s.replace(/<br\s*\/?>/gi, ' — ').replace(/<[^>]*>/g, '')
  .replace(/&amp;/g, '&').replace(/&middot;/g, '·').replace(/&nbsp;/g, ' ')
  .replace(/&mdash;/g, '—').replace(/&frac12;/g, '½')
  .replace(/\s+/g, ' ').trim();

const pageData = new Map(); // "16" -> { title, subtitle, specs, figures, blocks }
const skuPage = new Map();  // sku -> ["16", ...]

for (const file of fs.readdirSync(PAGEHTML).filter(f => /^page-.*\.html$/.test(f)).sort()) {
  const html = fs.readFileSync(path.join(PAGEHTML, file), 'utf8');
  const page = file.replace('page-', '').replace('.html', '');

  const title = clean((html.match(/<h1 class="cx-title">([\s\S]*?)<\/h1>/) || [])[1] || '');
  const subtitle = clean((html.match(/<p class="cx-subtitle">([\s\S]*?)<\/p>/) || [])[1] || '');
  // The file names follow the old SteriTrays PDF; the page chip carries the real
  // CandelX page number (page-16.html is CandelX page 10). Display THAT one.
  const pdfPage = Number(clean((html.match(/class="page-chip">([\s\S]*?)</) || [])[1] || '')
    .replace(/^Page\s*/i, '')) || null;

  const specs = {};
  for (const m of html.matchAll(/<span class="spec-item">([\s\S]*?)<\/span>/g)) {
    const txt = clean(m[1]);
    const i = txt.indexOf(':');
    if (i > 0) specs[txt.slice(0, i).trim()] = txt.slice(i + 1).trim();
  }

  // <figure> units pair an image with its caption; a caption marks a detail shot.
  const figures = [];
  const seen = new Set();
  for (const m of html.matchAll(/<figure\b[^>]*>([\s\S]*?)<\/figure>/g)) {
    const src = (m[1].match(/src="images\/([^"]+)"/) || [])[1];
    if (!src) continue;
    const capHtml = (m[1].match(/<figcaption[^>]*>([\s\S]*?)<\/figcaption>/) || [])[1] || '';
    const cap = clean(capHtml);
    // A caption may lead with <span class="code">CXGK-9910</span> — keep the
    // article number and the printed description apart.
    const code = clean((capHtml.match(/<span class="code">([\s\S]*?)<\/span>/) || [])[1] || '');
    const capText = clean(capHtml.replace(/<span class="code">[\s\S]*?<\/span>/, ''));
    figures.push({ i: m.index, src, caption: cap, code, capText });
    seen.add(src);
  }
  // images outside any <figure>
  for (const m of html.matchAll(/<img\b[^>]*>/g)) {
    const src = (m[0].match(/src="images\/([^"]+)"/) || [])[1];
    if (src && !seen.has(src)) { figures.push({ i: m.index, src, caption: '', code: '', capText: '' }); seen.add(src); }
  }
  figures.sort((a, b) => a.i - b.i);

  // heading blocks, for pages that print several products
  const toks = [];
  for (const m of html.matchAll(/<h3[^>]*>([\s\S]*?)<\/h3>/g)) toks.push({ i: m.index, t: 'H', v: clean(m[1]) });
  for (const f of figures) toks.push({ i: f.i, t: 'I', v: f.src });
  for (const m of html.matchAll(/class="art-no">([^<]+)</g)) {
    const sku = clean(m[1]);
    toks.push({ i: m.index, t: 'A', v: sku });
    if (!skuPage.has(sku)) skuPage.set(sku, []);
    if (!skuPage.get(sku).includes(page)) skuPage.get(sku).push(page);
  }
  // The PRF pages print article numbers as plain text instead of in a table
  // cell, so scan for the pattern too. Repeats are dropped per block below.
  for (const m of html.matchAll(/\bCX[A-Z]+-\d+\b/g)) toks.push({ i: m.index, t: 'A', v: m[0] });

  toks.sort((a, b) => a.i - b.i);

  const blocks = [];
  let cur = { head: null, imgs: [], arts: [] };
  for (const t of toks) {
    if (t.t === 'H') { blocks.push(cur); cur = { head: t.v, imgs: [], arts: [] }; }
    else if (t.t === 'I') cur.imgs.push(t.v);
    else if (!cur.arts.includes(t.v)) cur.arts.push(t.v);
  }
  blocks.push(cur);

  pageData.set(page, { page, pdfPage, title, subtitle, specs, figures, blocks });
}

/* ─────────────── size rows from the pristine snapshot ─────────────── */
const srcTs = fs.readFileSync(SIZESRC, 'utf8');
const marker = 'export const families: CatFamily[] = [';
const tail = srcTs.slice(srcTs.indexOf(marker) + marker.length - 1);
const oldFamilies = JSON.parse(tail.slice(0, tail.lastIndexOf('];') + 1));
const oldBySlug = new Map(oldFamilies.map(f => [f.slug, f]));
const sizeBySku = new Map();
for (const f of oldFamilies) for (const s of f.sizes) if (!sizeBySku.has(s.sku)) sizeBySku.set(s.sku, s);

const lidSkus = new Set();
for (const { blocks } of pageData.values())
  for (const b of blocks) if (b.head && /\blids?\b/i.test(b.head)) for (const a of b.arts) lidSkus.add(a);

const prefixOf = s => (s.match(/^([A-Z]+)/) || [])[1] || s;
const imgSize = src => {
  const m = src.match(/-(\d+)x(\d+)\.[a-z]+$/i);
  return m ? Math.max(+m[1], +m[2]) : 9999;
};
const pad = p => String(p).padStart(2, '0');

/* A figure caption prints whatever the catalogue has: sometimes a name and a
   spec ("Goldman fox scissors" / "TC · 13 cm"), sometimes only a spec
   ("1 × 2 teeth" / "12.5 cm"), often nothing at all. Nothing is invented — a
   part that starts with a letter is the name, the rest is the spec line. */
function splitCaption(capText) {
  if (!capText) return { name: null, note: null };
  const parts = capText.split('—').map(s => s.trim()).filter(Boolean);
  if (!parts.length) return { name: null, note: null };
  if (/^[A-Za-z]/.test(parts[0])) {
    return { name: parts[0], note: parts.slice(1).join(' · ') || null };
  }
  return { name: null, note: parts.join(' · ') };
}

/* ─────────────── build ─────────────── */
const wanted = new Set();
const out = [];
const report = [];
const usedSkus = new Set();

for (const cfg of PRODUCTS) {
  const pages = cfg.pages.map(pad);
  const pd = pages.map(p => pageData.get(p)).filter(Boolean);

  // ---- sizes ----
  let sizes = [];
  if (cfg.fromSlug) {
    const f = oldBySlug.get(cfg.fromSlug);
    if (f) sizes = f.sizes.map(s => ({ ...s }));
  } else {
    const skus = [];
    for (const p of pd) for (const b of p.blocks) for (const a of b.arts) {
      if (cfg.only && !cfg.only.includes(prefixOf(a))) continue;
      if (!skus.includes(a)) skus.push(a);
    }
    sizes = skus.map(sku => sizeBySku.get(sku)).filter(Boolean).map(s => ({ ...s }));
  }
  sizes = sizes.map(s => ({ ...s, variant: prefixOf(s.sku), isLid: lidSkus.has(s.sku) }));
  for (const s of sizes) usedSkus.add(s.sku);

  const prefixes = [...new Set(sizes.map(s => s.variant))];

  // ---- images ----
  let pool;
  if (cfg.blockScoped) {
    const blocks = pd.flatMap(p => p.blocks).filter(b =>
      b.arts.some(a => cfg.only ? cfg.only.includes(prefixOf(a)) : prefixes.includes(prefixOf(a))));
    const srcs = new Set(blocks.flatMap(b => b.imgs));
    pool = pd.flatMap(p => p.figures).filter(f => srcs.has(f.src));
  } else {
    pool = pd.flatMap(p => p.figures);
  }

  const captioned = pool.filter(f => f.caption);
  // Keep the catalogue's own order — the main shot is printed first. (Sorting by
  // pixel size picked the wrong photo, e.g. the chamfer tray instead of the round.)
  const plain = pool.filter(f => !f.caption);

  const hero = cfg.hero || plain[0]?.src || captioned[0]?.src || null;
  const heroAlt = cfg.heroAlt || (plain[1] ? plain[1].src : null);
  // figureGroups pages have no detail shots — every captioned figure is a
  // product in its own right and becomes a block below.
  const details = cfg.figureGroups ? [] :
    captioned.filter(f => f.src !== hero && f.src !== heroAlt)
      .map(f => ({ src: `/catalogue/img/${f.src}`, caption: f.caption, flag: imgSize(f.src) < 200 ? 'low_res' : 'ok' }));

  // Sub-sections: a page that prints each variant as its own block with its own
  // photos and table (transportation baskets: Steel / Aluminum; bur holders:
  // four holder families). Shown separately on the product page, not combined.
  const groups = [];
  // Each captioned figure is its own product (PRF surgical set, p42).
  if (cfg.figureGroups) {
    for (const f of captioned.filter(x => x.code)) {
      const { name, note } = splitCaption(f.capText);
      const s = sizeBySku.get(f.code);
      groups.push({
        label: name || f.code,
        code: f.code,
        note,
        images: [`/catalogue/img/${f.src}`],
        sizes: s ? [{ ...s, variant: prefixOf(s.sku), isLid: lidSkus.has(s.sku) }] : [],
      });
      wanted.add(f.src);
    }
  }
  if (cfg.groups) {
    for (const p of pd) for (const b of p.blocks) {
      if (!b.head) continue;
      const gSizes = b.arts.map(a => sizeBySku.get(a)).filter(Boolean)
        .map(s => ({ ...s, variant: prefixOf(s.sku), isLid: lidSkus.has(s.sku) }));
      const figs = p.figures.filter(f => b.imgs.includes(f.src));
      const gImgs = figs.filter(f => !f.caption).map(f => f.src);
      if (!gSizes.length && !gImgs.length) continue;
      for (const s of gImgs) wanted.add(s);
      // The same heading can repeat across two pages (silicon "Color E — Blue"
      // is on both p62 and p63) — Hassan asked for those combined, not listed twice.
      const existing = groups.find(g => g.label === b.head);
      if (existing) {
        for (const im of gImgs.map(s => `/catalogue/img/${s}`)) {
          if (!existing.images.includes(im)) existing.images.push(im);
        }
        for (const s of gSizes) if (!existing.sizes.some(x => x.sku === s.sku)) existing.sizes.push(s);
        continue;
      }
      groups.push({
        label: b.head,
        code: null,
        note: null,
        images: gImgs.map(s => `/catalogue/img/${s}`),
        sizes: gSizes,
      });
    }
  }

  if (hero) wanted.add(hero);
  if (heroAlt) wanted.add(heroAlt);
  for (const f of captioned) if (f.src !== hero && f.src !== heroAlt) wanted.add(f.src);

  const specs = Object.assign({}, ...pd.map(p => p.specs));
  const subtitle = cfg.subtitle ?? (pd[0]?.subtitle || '');
  const flag = !hero ? 'missing' : imgSize(hero) < 200 ? 'low_res' : 'ok';

  out.push({
    slug: cfg.slug,
    prefix: prefixes.join(' / '),
    prefixes,
    section: cfg.section,
    name: cfg.name,
    subtitle,
    summary: '',
    catalogueTitle: pd[0]?.title || '',
    variants: (cfg.variants || []).filter(v => prefixes.includes(v.code)),
    needsReview: Boolean(cfg.review) || flag !== 'ok' || sizes.length === 0,
    notes: [],
    specs,
    image: hero ? `/catalogue/img/${hero}` : null,
    imageAlt: heroAlt ? `/catalogue/img/${heroAlt}` : null,
    imageFlag: flag,
    details,
    groups,
    // "instruments" = a set whose members are separate products, shown as a
    // grid of blocks rather than one photo with a size table.
    groupLayout: cfg.figureGroups ? 'instruments' : null,
    // The page-html FILE numbers follow the old SteriTrays PDF; show the CandelX
    // page printed on the page chip instead (page-16.html is CandelX page 10).
    sourcePages: pd.map(p => p.pdfPage).filter(Boolean),
    sizes,
  });

  report.push(`${cfg.slug.padEnd(30)} ${cfg.section.slice(0, 22).padEnd(23)} p${String(pd.map(p => p.pdfPage).join(',')).padEnd(6)} ${String(sizes.length).padStart(3)} sizes ${String(details.length).padStart(2)} thumb ${groups.length ? String(groups.length) + ' grp' : '     '} ${heroAlt ? 'alt ' : '    '}${flag}`);
}

/* ─────────────── copy images ─────────────── */
fs.rmSync(OUTIMG, { recursive: true, force: true });
