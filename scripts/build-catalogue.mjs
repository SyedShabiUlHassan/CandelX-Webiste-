/* ─────────── real pixel size of an image, from its own header ───────────
   The photo box used a fixed 4:3, so a tall diagram (the orthodontic mirror
   set is 2437x4261) shrank to fit and looked tiny. Read the true shape and
   let the frame follow it. Filenames are not trusted — many carry no size. */
function imageSize(webPath) {
  if (!webPath || !webPath.startsWith('/')) return null;
  const file = path.join(ROOT, 'site/public', webPath);
  if (!fs.existsSync(file)) return null;
  const b = fs.readFileSync(file);
  try {
    if (b.length > 24 && b.readUInt32BE(0) === 0x89504e47)           // PNG
      return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
    if (b[0] === 0xff && b[1] === 0xd8) {                             // JPEG
      let i = 2;
      while (i < b.length - 9) {
        if (b[i] !== 0xff) { i++; continue; }
        const m = b[i + 1];
        if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc)
          return { w: b.readUInt16BE(i + 7), h: b.readUInt16BE(i + 5) };
        i += 2 + b.readUInt16BE(i + 2);
      }
    }
    if (b.length > 30 && b.toString('ascii', 0, 4) === 'RIFF'         // WebP (VP8X/VP8L/VP8 )
        && b.toString('ascii', 8, 12) === 'WEBP') {
      const fmt = b.toString('ascii', 12, 16);
      if (fmt === 'VP8X') return { w: (b.readUIntLE(24, 3) & 0xffffff) + 1, h: (b.readUIntLE(27, 3) & 0xffffff) + 1 };
      if (fmt === 'VP8 ') return { w: b.readUInt16LE(26) & 0x3fff, h: b.readUInt16LE(28) & 0x3fff };
      if (fmt === 'VP8L') {
        const n = b.readUInt32LE(21);
        return { w: (n & 0x3fff) + 1, h: ((n >> 14) & 0x3fff) + 1 };
      }
    }
  } catch { /* unreadable header — fall back to the default box */ }
  return null;
}

function imageAspect(webPath) {
  const d = imageSize(webPath);
  return d && d.h ? +(d.w / d.h).toFixed(4) : null;
}

/* Every image path the site renders, with its real pixel size.
   Without width/height on an <img> the browser cannot reserve space and the
   text jumps as each photo arrives — Google scores that as layout shift.
   Audit 2026-09-14, M-06. */
function collectImageDims(families) {
  const dims = {};
  const add = (p) => {
    if (!p || dims[p] !== undefined) return;
    const d = imageSize(p);
    if (d) dims[p] = [d.w, d.h];
  };
  for (const f of families) {
    add(f.image); add(f.imageAlt);
    (f.images || []).forEach(add);
    (f.details || []).forEach((d) => add(d.src));
    (f.groups || []).forEach((g) => {
      (g.images || []).forEach(add);
      (g.sizes || []).forEach((s) => add(s.image));
    });
    (f.sizes || []).forEach((s) => add(s.image));
  }
  return dims;
}

